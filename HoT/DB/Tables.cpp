template <class DB>
static bool ReloadTable(WowClientDB_Base* db) {
    return Reload(*static_cast<DB*>(db), __FILE__, __LINE__);
}

template <class T>
static Table Make(WowClientDB<T>& db) {
    return { T::GetFilename(), &db, ReloadTable<WowClientDB<T>> };
}

template <class T>
static Table Make(WowClientDB_RLE<T>& db) {
    return { T::GetFilename(), &db, ReloadTable<WowClientDB_RLE<T>> };
}

